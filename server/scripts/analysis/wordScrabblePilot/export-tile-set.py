"""Sentence Tiles — export the pilot's tile set as the server module the game deals from.

Reads (all under data/):
  tiles.tsv              every HSK 1–3 det entry (export-tiles.sql): word, difficulty, freq, POS json, def0
  r3-points-all.json     tile-points.py output: every tile with connectivity ≥ 3, its play rate and points

Writes:
  server/services/sentenceTiles/tileSet.zh.ts — GENERATED; do not hand-edit. Re-run this script instead.

The module holds:
  ZH_TILES          one row per qualifying tile: word, main POS, points, connectivity
  ZH_FORCED_COUNTS  the bag's function-word skeleton (copies per bag) — build-samples.py's round-3
                    forced list, minus every tile below the connectivity floor
  ZH_POS_QUOTA      how many tiles of each POS a 100-tile bag holds (forced copies included)

Consumed by: server/services/sentenceTiles/bag.ts → buildBag.
Docs: docs/SENTENCE_TILES_GAME.md § "Tiles and the bag", docs/BACKLOG.md § 10.

Usage: python3 export-tile-set.py
"""
import csv, json, os

HERE = os.path.dirname(os.path.abspath(__file__))
DATA = os.path.join(HERE, 'data')
OUT = os.path.join(HERE, '..', '..', '..', 'services', 'sentenceTiles', 'tileSet.zh.ts')

rows = list(csv.reader(open(f'{DATA}/tiles.tsv'), delimiter='\t'))
pos = {r[0]: (json.loads(r[3])[0] if r[3] else 'none') for r in rows}
points = json.load(open(f'{DATA}/r3-points-all.json'))

# build-samples.py's round-3 forced list (the bag's "vowels"), copied so the server does not
# depend on the analysis folder. Tiles under the connectivity floor are dropped below.
forced = {'我': 3, '你': 3, '他': 2, '她': 1, '我们': 1, '这': 1, '什么': 1,
          '了': 3, '的': 2, '着': 1, '吗': 2, '吧': 1, '呢': 1,
          '不': 2, '很': 2, '都': 1, '也': 1, '就': 1,
          '是': 2, '有': 2, '在': 1, '去': 1, '要': 1,
          '好': 2, '对': 1, '从': 1, '和': 1, '但是': 1,
          '一个': 1, '一点': 1, '一下': 1, '一些': 1}
forced = {w: n for w, n in forced.items() if w in points}
quota = {'adverb': 9, 'verb': 23, 'noun': 25, 'adjective': 8, 'interjection': 1}

tiles = sorted(
    ({'word': w, 'pos': pos.get(w, 'none'), 'points': p['points'], 'connectivity': p['connectivity']}
     for w, p in points.items()),
    key=lambda t: (t['points'], t['word']))

def js(v):
    return json.dumps(v, ensure_ascii=False)

lines = [
    '// GENERATED by server/scripts/analysis/wordScrabblePilot/export-tile-set.py — do not hand-edit.',
    '// Source: the round-3 pilot (connectivity ≥ 3, points from play rate at rack 11).',
    '// Consumed by server/services/sentenceTiles/bag.ts. Docs: docs/SENTENCE_TILES_GAME.md.',
    '',
    'export interface TileDef {',
    '  /** The det headword (`dictionaryentries_zh.word1`). One tile = one word, however many characters. */',
    '  word: string;',
    '  /** The first POS in det `partsOfSpeech` — only used to compose the bag. */',
    '  pos: string;',
    '  /** Face value: 1 + round(9 × (1 − play rate)). */',
    '  points: number;',
    '  /** AI connectivity rating 1–5 (connectivity-rubric.md); every tile here is ≥ 3. */',
    '  connectivity: number;',
    '}',
    '',
    'export const ZH_TILES: readonly TileDef[] = [',
]
lines += [f'  {{ word: {js(t["word"])}, pos: {js(t["pos"])}, points: {t["points"]}, connectivity: {t["connectivity"]} }},' for t in tiles]
lines += [
    '];',
    '',
    '/** Copies of each function word every bag starts with. */',
    f'export const ZH_FORCED_COUNTS: Readonly<Record<string, number>> = {js(forced)};',
    '',
    '/** Tiles of each POS in a 100-tile bag, forced copies included; the rest is topped up from any POS. */',
    f'export const ZH_POS_QUOTA: Readonly<Record<string, number>> = {js(quota)};',
    '',
]
os.makedirs(os.path.dirname(OUT), exist_ok=True)
open(OUT, 'w').write('\n'.join(lines))
print(f'{len(tiles)} tiles, {sum(forced.values())} forced copies → {os.path.normpath(OUT)}')
