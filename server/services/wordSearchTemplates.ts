/**
 * Word Search — fixed placement templates (fallback path), one set per board.
 *
 * See docs/WORD_SEARCH_TEMPLATES.md for the full design. Used by
 * `generateWordSearchGrid` (wordSearchGrid.ts) once random snaking placement
 * has failed `RANDOM_GRID_ATTEMPTS` whole-grid regenerations in a row.
 *
 * A template tiles a board's fixed hole pattern into disjoint "slots", each an
 * ordered path of exactly 4 orthogonally-adjacent cells, one slot per word. A word
 * of length 4 fills a whole slot; a shorter word takes a random contiguous run
 * within its slot (see wordSearchGrid.ts), leaving the rest of that slot as
 * ordinary filler.
 *
 *   7×6 (`WORD_SEARCH_BOARDS.standard`): 9 slots, 36 of 42 cells (86%); 6 holes, the
 *     four corners + the two centre cells.
 *   6×5 (`WORD_SEARCH_BOARDS.compact`, the tower flp's break): 7 slots, 28 of 30
 *     cells (93%); 2 holes, diagonal corners. Random placement almost never fits a
 *     full-length board at this density, so these templates carry it.
 *
 * Generated by server/scripts/generate-word-search-templates.js (not at runtime) and
 * verified by server/__tests__/wordSearchTemplates.test.ts for: pieces of exactly 4
 * cells, every consecutive pair orthogonally adjacent, no piece cell adjacent to more
 * than 2 same-piece cells (rules out T/plus-shaped pieces, which can't be walked as a
 * single path), no piece closing into a 2×2 loop (a cycle would read as a word in
 * several directions), no overlaps, and full coverage of the non-hole cells.
 *
 * Depended on by: docs/WORD_SEARCH_TEMPLATES.md, docs/WORD_SEARCH_GAME.md § 2.
 */

export interface WordSearchTemplate {
  /** One slot per word, each an ordered path of exactly 4 [row, col] cells. */
  slots: [number, number][][];
}

/** Every template of one board shape. All of a set's templates share its holes. */
export interface WordSearchTemplateSet {
  rows: number;
  cols: number;
  /** The cells no slot covers; they always take filler. */
  holes: [number, number][];
  templates: WordSearchTemplate[];
}

