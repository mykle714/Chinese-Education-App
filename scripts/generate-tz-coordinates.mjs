#!/usr/bin/env node
/**
 * generate-tz-coordinates.mjs — writes src/timeOfDay/tzCoordinates.ts, the
 * IANA timezone → representative [lat, lon] table the Deck Tower's time of day uses to
 * compute a sunrise and sunset without asking the device for its location
 * (docs/DECK_TOWER.md § "Time of day").
 *
 * Source: the system tzdb — `zone.tab` (each canonical zone's principal city, ISO 6709
 * ±DDMM[SS]±DDDMM[SS]) and `tzdata.zi`'s `L target alias` link lines, so legacy names a
 * browser may still report (`Asia/Calcutta`) resolve to their canonical zone's city.
 * Coordinates are rounded to 0.1° (~11 km): the sky only needs to be loosely right.
 *
 * Usage (from the repo root): node scripts/generate-tz-coordinates.mjs [zoneinfoDir]
 *   zoneinfoDir defaults to /usr/share/zoneinfo.
 */
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = process.argv[2] ?? "/usr/share/zoneinfo";
const OUT = "src/timeOfDay/tzCoordinates.ts";

/** One ISO 6709 component (`+4230`, `-0734512`) → decimal degrees. `degDigits` is 2 for latitude, 3 for longitude. */
function iso6709(part, degDigits) {
    const sign = part[0] === "-" ? -1 : 1;
    const digits = part.slice(1);
    const deg = Number(digits.slice(0, degDigits));
    const min = Number(digits.slice(degDigits, degDigits + 2));
    const sec = Number(digits.slice(degDigits + 2) || 0);
    return sign * (deg + min / 60 + sec / 3600);
}

const coords = new Map();
for (const line of readFileSync(join(dir, "zone.tab"), "utf8").split("\n")) {
    if (!line || line.startsWith("#")) continue;
    const [, at, zone] = line.split("\t");
    const m = /^([+-]\d+)([+-]\d+)$/.exec(at);
    if (!m) continue;
    coords.set(zone, [iso6709(m[1], 2), iso6709(m[2], 3)]);
}

// Links (alias → canonical). Only aliases whose target has a city are kept.
let links = 0;
for (const line of readFileSync(join(dir, "tzdata.zi"), "utf8").split("\n")) {
    if (!line.startsWith("L ")) continue;
    const [, target, alias] = line.split(" ");
    const at = coords.get(target);
    if (at && !coords.has(alias)) {
        coords.set(alias, at);
        links++;
    }
}

const round = (v) => Math.round(v * 10) / 10;
const rows = [...coords.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([zone, [lat, lon]]) => `    "${zone}": [${round(lat)}, ${round(lon)}],`);

const out = `/**
 * tzCoordinates.ts — GENERATED by scripts/generate-tz-coordinates.mjs; do not edit by hand.
 *
 * Each IANA timezone (and the legacy aliases tzdb links to one) → its principal city's
 * [latitude, longitude] in degrees, north and east positive, rounded to 0.1°. The Deck
 * Tower's time of day reads it to place the learner loosely on the globe for the sunrise
 * and sunset (docs/DECK_TOWER.md § "Time of day"). A wide zone collapses to one city —
 * accepted: the sky only needs to be roughly right.
 *
 * Depended on by: src/timeOfDay/sunTimes.ts (\`deviceLocation\`).
 */
export const TZ_COORDINATES: Readonly<Record<string, readonly [number, number]>> = {
${rows.join("\n")}
};
`;
writeFileSync(OUT, out);
console.log(`${OUT}: ${coords.size} zones (${links} aliases)`);
