/**
 * Word Search — fixed 9×6 placement templates (fallback path).
 *
 * See docs/WORD_SEARCH_TEMPLATES.md for the full design. Used by
 * `generateWordSearchGrid` (wordSearchGrid.ts) once random snaking placement
 * has failed `RANDOM_GRID_ATTEMPTS` whole-grid regenerations in a row.
 *
 * Sized for TOTAL_WORDS = 12 (raised from 10 on 2026-08-23): each template
 * tiles the same fixed 6-hole 9×6 pattern (the four board corners + the two
 * cells at the grid's center — the cells NOT covered by any slot below) into
 * 12 disjoint "slots," each an ordered path of exactly 4 orthogonally-adjacent
 * cells. A word of length 4 fills a whole slot; a shorter word takes a random
 * contiguous run within its slot (see wordSearchGrid.ts), leaving the rest of
 * that slot as ordinary filler. Only 6 holes remain at 12 words (down from 14
 * at 10 words — 48 of 54 cells are now slot cells, an 89%-full board), so
 * random placement is expected to fall back to template mode far more often
 * than it did at 10 words; template mode still guarantees a fit by
 * construction regardless.
 *
 * Generated by a one-off backtracking tiling script (not at runtime) and
 * verified for: exactly 12 pieces of exactly 4 cells, every consecutive pair
 * within a piece orthogonally adjacent, no piece cell adjacent to more than 2
 * same-piece cells (rules out T/plus-shaped pieces, which can't be walked as
 * a single path), no overlaps, and full coverage of the 48 non-hole cells.
 */

export interface WordSearchTemplate {
  /** 12 slots, each an ordered path of exactly 4 [row, col] cells. */
  slots: [number, number][][];
}

